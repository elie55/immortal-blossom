#!/usr/bin/env python3
"""Build the Immortal Blossoms vertical slice.

    python3 tools/build_game.py            # data module + dist/ bundle
    python3 tools/build_game.py --data     # only regenerate game/js/gamedata.js

1. game/js/gamedata.js: every record in data/ as one ES module (the game reads ids, never files).
2. dist/index.html: game/index.html with its stylesheets and ES modules inlined in one page, plus
   dist/assets/ copied from game/assets/. The source stays plain ES modules (it runs as is from a local
   server); the bundle hoists every module into one scope, so the build fails on any top-level name
   that two modules both declare, on aliased imports, and on imports of names a module does not export.
"""
import glob
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = os.path.join(ROOT, 'game')
DIST = os.path.join(ROOT, 'dist')


def build_data():
    records = []
    for f in sorted(glob.glob(os.path.join(ROOT, 'data', '**', '*.json'), recursive=True)):
        with open(f, encoding='utf8') as fh:
            records.extend(json.load(fh)['records'])
    body = json.dumps({'records': records}, ensure_ascii=False, separators=(',', ':'))
    out = os.path.join(GAME, 'js', 'gamedata.js')
    with open(out, 'w', encoding='utf8') as fh:
        fh.write('// Generated by tools/build_game.py from data/. Do not edit.\n')
        fh.write('export const GAME_DATA = ' + body + ';\n')
    print(f'gamedata.js: {len(records)} records, {len(body) // 1024} KB')
    # The art the build ships: the game falls back gracefully when a heroine or enemy has no picture yet.
    files = sorted(os.path.relpath(p, os.path.join(GAME, 'assets')).replace(os.sep, '/')
                   for p in glob.glob(os.path.join(GAME, 'assets', '**', '*.webp'), recursive=True))
    with open(os.path.join(GAME, 'js', 'assets.js'), 'w', encoding='utf8') as fh:
        fh.write('// Generated by tools/build_game.py: every image in game/assets.\n')
        fh.write('export const ASSET_FILES = new Set(' + json.dumps(files) + ');\n')
    print(f'assets.js: {len(files)} images')


IMPORT_RE = re.compile(r"^import\s+(?:(?:\*\s+as\s+(\w+)|\{([^}]*)\})\s+from\s+)?'([^']+)';?[ \t]*$", re.M)
EXPORT_DECL_RE = re.compile(r'^export\s+(?:async\s+)?(?:function\*?|const|let|class|var)\s+(\w+)', re.M)
EXPORT_LIST_RE = re.compile(r'^export\s*\{([^}]*)\};?[ \t]*$', re.M)
TOP_DECL_RE = re.compile(r'^(?:export\s+)?(?:async\s+)?(?:function\*?\s+(\w+)|(?:const|let|var|class)\s+(\w+))', re.M)


class Module:
    def __init__(self, path):
        self.path = path
        self.name = os.path.relpath(path, os.path.join(GAME, 'js'))
        with open(path, encoding='utf8') as fh:
            self.src = fh.read()
        self.imports = []  # (namespace or None, [names], resolved path)
        for m in IMPORT_RE.finditer(self.src):
            ns, names, rel = m.group(1), m.group(2), m.group(3)
            target = os.path.normpath(os.path.join(os.path.dirname(path), rel))
            lst = []
            if names:
                for n in [x.strip() for x in names.split(',') if x.strip()]:
                    if ' as ' in n:
                        raise SystemExit(f'{self.name}: aliased import "{n}" is not supported')
                    lst.append(n)
            self.imports.append((ns, lst, target))
        self.exports = set(EXPORT_DECL_RE.findall(self.src))
        for m in EXPORT_LIST_RE.finditer(self.src):
            self.exports.update(x.strip() for x in m.group(1).split(',') if x.strip())
        self.top = set(a or b for a, b in TOP_DECL_RE.findall(self.src))

    def body(self):
        s = IMPORT_RE.sub('', self.src)
        s = EXPORT_LIST_RE.sub('', s)
        s = re.sub(r'^export\s+(?=(?:async\s+)?(?:function|const|let|class|var)\b)', '', s, flags=re.M)
        return s.strip('\n')


def bundle():
    entry = os.path.join(GAME, 'js', 'main.js')
    mods, order, seen = {}, [], set()

    def visit(p, stack):
        if p in seen:
            return
        if p in stack:
            return  # cycle: hoisting puts both in one scope, the order of the rest still holds
        if p not in mods:
            if not os.path.exists(p):
                raise SystemExit(f'missing module {p}')
            mods[p] = Module(p)
        stack.add(p)
        for _, _, t in mods[p].imports:
            visit(t, stack)
        stack.discard(p)
        if p not in seen:
            seen.add(p)
            order.append(p)

    visit(entry, set())
    errors = []
    owner = {}
    for p in order:
        for n in mods[p].top:
            if n in owner and owner[n] != p:
                errors.append(f'top-level name "{n}" is declared in both {mods[owner[n]].name} and {mods[p].name}')
            owner[n] = p
    namespaces = {}
    for p in order:
        for ns, names, t in mods[p].imports:
            for n in names:
                if n not in mods[t].exports:
                    errors.append(f'{mods[p].name} imports "{n}", which {mods[t].name} does not export')
            if ns:
                if ns in namespaces and namespaces[ns] != t:
                    errors.append(f'namespace "{ns}" names two modules')
                if ns in owner:
                    errors.append(f'namespace "{ns}" clashes with a top-level name in {mods[owner[ns]].name}')
                namespaces[ns] = t
    if errors:
        raise SystemExit('bundle errors:\n  ' + '\n  '.join(errors))
    parts = ['// Immortal Blossoms vertical slice, bundled by tools/build_game.py']
    for ns, t in sorted(namespaces.items()):
        getters = ', '.join(f'get {n}() {{ return {n}; }}' for n in sorted(mods[t].exports))
        parts.append(f'const {ns} = Object.freeze({{ {getters} }});')
    for p in order:
        parts.append(f'// ===== {mods[p].name} =====\n' + mods[p].body())
    js = '\n'.join(parts)

    with open(os.path.join(GAME, 'index.html'), encoding='utf8') as fh:
        html = fh.read()

    def inline_css(m):
        with open(os.path.join(GAME, m.group(1)), encoding='utf8') as fh:
            return '<style>\n' + fh.read() + '\n</style>'
    html = re.sub(r'<link rel="stylesheet" href="(css/[^"]+)">', inline_css, html)
    script = '<script type="module">\n' + js.replace('</script', '<\\/script') + '\n</script>'
    html = html.replace('<script type="module" src="js/main.js"></script>', script)
    if os.path.exists(DIST):
        shutil.rmtree(DIST)
    os.makedirs(DIST)
    with open(os.path.join(DIST, 'index.html'), 'w', encoding='utf8') as fh:
        fh.write(html)
    # artifact.html: the same page without its document skeleton, which the artifact host adds itself
    frag = re.sub(r'<!doctype html>\s*|<html[^>]*>\s*|</html>\s*|<head>\s*|</head>\s*|<body>\s*|</body>\s*|<meta charset="utf-8">\s*', '', html, flags=re.I)
    frag = frag.replace('<title>Immortal Blossoms</title>', '<title>Immortal Blossoms Vertical Slice</title>', 1)
    with open(os.path.join(DIST, 'artifact.html'), 'w', encoding='utf8') as fh:
        fh.write(frag)
    shutil.copytree(os.path.join(GAME, 'assets'), os.path.join(DIST, 'assets'))
    size = os.path.getsize(os.path.join(DIST, 'index.html'))
    n = sum(len(fs) for _, _, fs in os.walk(os.path.join(DIST, 'assets')))
    print(f'dist/index.html: {len(order)} modules, {size // 1024} KB; {n} asset files')


if __name__ == '__main__':
    build_data()
    if '--data' not in sys.argv:
        bundle()
